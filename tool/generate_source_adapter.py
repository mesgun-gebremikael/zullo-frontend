"""Generate the compatibility adapter for canonical choice labels and API UI errors.
Never use tr() for names, messages, bios, answers or other user-authored content.
"""
import json
import re
from pathlib import Path
manifest = json.loads(Path('tool/catalog_manifest.json').read_text())
lines = ["import 'package:flutter/widgets.dart';", "import 'app_localizations.dart';", "import 'app_localizations_sv.dart';", '', '// Generated by tool/generate_source_adapter.py. Do not edit manually.', 'extension ZulloLocalization on BuildContext {', '  AppLocalizations get l10n => Localizations.of<AppLocalizations>(this, AppLocalizations) ?? AppLocalizationsSv();', '  /// Canonical UI labels only. Never translate user-authored content here.', '  String tr(String source) {', '    switch (source) {']
for source, key in manifest.items():
    if '{value' not in source:
        lines.append(f'      case {json.dumps(source,ensure_ascii=False)}: return l10n.{key};')
lines += ['    }']
for source, key in manifest.items():
    if '{value' not in source:
        continue
    tokens = re.split(r'(\{value\d+\})', source)
    pattern = '^' + ''.join('(.*?)' if re.fullmatch(r'\{value\d+\}', token) else re.escape(token) for token in tokens) + '$'
    count = len(re.findall(r'\{value\d+\}', source))
    # JSON escapes backslashes; escape Dart interpolation anchors separately.
    pattern_literal = json.dumps(pattern, ensure_ascii=False).replace('$', '\\$')
    args = ', '.join(f'match.group({i})!' for i in range(1, count+1))
    lines += ['    {', f'      final match = RegExp({pattern_literal}, dotAll: true).firstMatch(source);', f'      if (match != null) {{ return l10n.{key}({args}); }}', '    }']
lines += ['    return source;', '  }', '}']
Path('lib/l10n/localization.dart').write_text('\n'.join(lines)+'\n')
