#!/usr/bin/env python3
"""Generate native notification copy from the same reviewed Flutter catalogs.

Run from repository root; --check rejects stale/missing generated resources.
Android/iOS select these strings using the OS's notification language. No names,
messages or other user-authored content belong in these static resources.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
COPY = {
    'zullo_message_body': 'newMessageNotification',
    'zullo_match_title': 'itSAMatch',
    'zullo_match_body': 'youVeMatchedOpenChatsToSayHello',
    'zullo_superlike_body': 'youReceivedASuperlike',
}
GROUP = 'D9C6A3523794D7EA8F2702F3'
BUILD = '191761628BC0E5DA4FB44F7F'


def ready_locales():
    text = (ROOT / 'lib/l10n/locale_catalog.dart').read_text()
    return re.findall(r"'([^']+)'", text.split('static const ready =', 1)[1].split(';', 1)[0])


def resource_id(locale):
    return hashlib.sha256(('zullo-native-notification-' + locale).encode()).hexdigest()[:24].upper()


def android_value(value):
    value = value.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
    return escape(value)


def ios_locale(locale):
    return locale.replace('_', '-')


def generate():
    outputs = {}
    locales = ready_locales()
    for locale in locales:
        data = json.loads((ROOT / f'lib/l10n/app_{locale}.arb').read_text())
        messages = {key: data[arb_key] for key, arb_key in COPY.items()}
        assert all(isinstance(value, str) and value.strip() and '{value' not in value for value in messages.values()), locale
        android = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_notification_resources.py. -->\n<resources>\n'
        android += ''.join(f'    <string name="{key}">{android_value(value)}</string>\n' for key, value in messages.items())
        android += '</resources>\n'
        qualifier = 'values' if locale == 'en' else 'values-b+' + locale.replace('_', '+')
        outputs[ROOT / f'android/app/src/main/res/{qualifier}/notification_strings.xml'] = android
        ios = '// Generated by tool/generate_notification_resources.py.\n'
        ios += ''.join(f'{json.dumps(key)} = {json.dumps(value, ensure_ascii=False)};\n' for key, value in messages.items())
        outputs[ROOT / f'ios/Runner/{ios_locale(locale)}.lproj/Localizable.strings'] = ios
    pbx_path = ROOT / 'ios/Runner.xcodeproj/project.pbxproj'
    pbx = pbx_path.read_text()
    # Replace only this generator's deterministic entries, preserving all other
    # project resources and settings.
    refs = ''.join(f'\t\t{resource_id(locale)} /* {ios_locale(locale)} */ = {{isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = "{ios_locale(locale)}"; path = "{ios_locale(locale)}.lproj/Localizable.strings"; sourceTree = "<group>"; }};\n' for locale in locales)
    for locale in locales:
        pbx = re.sub(r'^\t\t' + resource_id(locale) + r' /\*.*?\*/ = .*?;\n', '', pbx, flags=re.M)
    pbx = pbx.replace('/* End PBXFileReference section */', refs + '/* End PBXFileReference section */')
    if f'{BUILD} /* Localizable.strings in Resources */ =' not in pbx:
        pbx = pbx.replace('/* End PBXBuildFile section */', f'\t\t{BUILD} /* Localizable.strings in Resources */ = {{isa = PBXBuildFile; fileRef = {GROUP} /* Localizable.strings */; }};\n/* End PBXBuildFile section */')
    group = f'\t\t{GROUP} /* Localizable.strings */ = {{\n\t\t\tisa = PBXVariantGroup;\n\t\t\tchildren = (\n'
    group += ''.join(f'\t\t\t\t{resource_id(locale)} /* {ios_locale(locale)} */,\n' for locale in locales)
    group += '\t\t\t);\n\t\t\tname = Localizable.strings;\n\t\t\tsourceTree = "<group>";\n\t\t};\n'
    pbx = re.sub(r'\t\t' + GROUP + r' /\* Localizable.strings \*/ = \{.*?\n\t\t\};\n', '', pbx, flags=re.S)
    pbx = pbx.replace('/* End PBXVariantGroup section */', group + '/* End PBXVariantGroup section */')
    runner_anchor = '\t\t\t\t97C147021CF9000F007C117D /* Info.plist */,\n'
    if f'\t\t\t\t{GROUP} /* Localizable.strings */,' not in pbx:
        assert runner_anchor in pbx
        pbx = pbx.replace(runner_anchor, runner_anchor + f'\t\t\t\t{GROUP} /* Localizable.strings */,\n')
    build_anchor = '\t\t\t\t97C146FC1CF9000F007C117D /* Main.storyboard in Resources */,\n'
    if f'\t\t\t\t{BUILD} /* Localizable.strings in Resources */,' not in pbx:
        assert build_anchor in pbx
        pbx = pbx.replace(build_anchor, build_anchor + f'\t\t\t\t{BUILD} /* Localizable.strings in Resources */,\n')
    regions = '\t\t\tknownRegions = (\n\t\t\t\tBase,\n' + ''.join(f'\t\t\t\t"{ios_locale(locale)}",\n' for locale in locales) + '\t\t\t);'
    pbx = re.sub(r'\t\t\tknownRegions = \(.*?\n\t\t\t\);', regions, pbx, count=1, flags=re.S)
    outputs[pbx_path] = pbx
    return outputs, locales


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, locales = generate()
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit('Stale native notification resources:\n' + '\n'.join(stale))
    print(f'{len(locales)} native notification languages validated' if args.check else f'Generated {len(locales)} Android/iOS notification languages')


if __name__ == '__main__':
    main()
